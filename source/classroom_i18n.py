def translate(text: str, language: str) -> str:
    """Translate visible Traditional Chinese UI text; preserve unknown/user text."""
    if language != "en_US" or not isinstance(text, str):
        return text
    translated = _TEXT.get(text)
    if translated is not None:
        return translated
    for pattern, render in _DYNAMIC:
        match = pattern.fullmatch(text)
        if match:
            return render(match)
    return text
